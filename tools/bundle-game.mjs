// bundle-game.mjs - folds the ~190 files of src/ into one dist/game.js for the itch
// build. itch.io unpacks at most 1000 files per HTML game (4 Nov 2026 the build had
// 1097), so the release ships this one file instead of src/. Run it (cloud: npm run
// bundle) after any change in src/; npm test fails while dist/game.js is stale.
// Not minified, so the code reads the same in the browser's error messages.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { srcHash } from './src-hash.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'dist', 'game.js');
execFileSync('npx', ['--yes', 'esbuild@0.24.0', 'src/main.js', '--bundle', '--format=esm',
  '--target=es2020', '--legal-comments=none', '--log-level=warning', `--outfile=${out}`],
  { cwd: root, stdio: 'inherit', shell: process.platform === 'win32' });
const body = readFileSync(out, 'utf8');
writeFileSync(out, `// src-hash: ${srcHash(root)}\n// Generated by tools/bundle-game.mjs from src/. Do not edit: edit src/ and re-run.\n${body}`);
console.log(`dist/game.js written (${(body.length / 1024).toFixed(0)} KB)`);
