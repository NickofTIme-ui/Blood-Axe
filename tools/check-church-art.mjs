const out=createCanvas(1000,620),g=out.getContext('2d');
g.fillStyle='#282326';g.fillRect(0,0,1000,620);
g.drawImage(church,100,10,700,420);
for(let i=0;i<4;i++)g.drawImage(sheet.canvas,i*sheet.fw,0,sheet.fw,sheet.fh,30+i*240,470,sheet.fw*.5,130);
const c=createCanvas(church.width,church.height),ctx=c.getContext('2d');ctx.drawImage(church,0,0);
const d=ctx.getImageData(0,0,c.width,c.height).data;
assert(d.some((v,i)=>i%4===3&&v===0),'Church must have transparent surroundings');
fs.writeFileSync('docs/church-art-review.png',out.toBuffer('image/png'));
console.log('Church transparent silhouette and four imported pallbearer poses passed',sheet.fw,sheet.fh);
