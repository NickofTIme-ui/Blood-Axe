import {createRequire} from 'node:module';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire('C:/Users/nickr/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/');
const {createCanvas,loadImage}=require('@napi-rs/canvas');
globalThis.document={createElement:()=>createCanvas(1,1)};
const {importFxStrip}=await import('../src/view/stripImporter.js');
const church=await loadImage('assets/env/village/town-church.png');
const bearers=await loadImage('assets/npcs/church-bearers.png');
const sheet=importFxStrip(bearers,{frames:4,columns:2,rows:2,height:260});
